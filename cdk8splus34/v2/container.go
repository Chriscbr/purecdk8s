// A single application container that you want to run within a pod.
type Container interface {
	// Arguments to the entrypoint.
	//
	// Returns: a copy of the arguments array, cannot be modified.
	Args() *[]*string
	// Entrypoint array (the command to execute when the container starts).
	//
	// Returns: a copy of the entrypoint array, cannot be modified.
	Command() *[]*string
	// The container image.
	Image() *string
	// Image pull policy for this container.
	ImagePullPolicy() ImagePullPolicy
	// Volume mounts configured for this container.
	Mounts() *[]*VolumeMount
	// The name of the container.
	Name() *string
	// Deprecated: - use `portNumber`.
	Port() *float64
	// The port number that was configured for this container.
	//
	// If undefined, either the container doesn't expose a port, or its port configuration is stored in the `ports` field.
	PortNumber() *float64
	// Ports exposed by this containers.
	//
	// Returns a copy, use `addPort` to modify.
	Ports() *[]*ContainerPort
	// The working directory inside the container.
	WorkingDir() *string
	// The environment of the container.
	Env() Env
	// Compute resources (CPU and memory requests and limits) required by the container. See: https://kubernetes.io/docs/concepts/configuration/manage-resources-containers/
	Resources() *ContainerResources
	// The restart policy of the container.
	RestartPolicy() ContainerRestartPolicy
	// The security context of the container.
	SecurityContext() ContainerSecurityContext
	// Add a port to expose from this container.
	AddPort(port *ContainerPort)
	// Mount a volume to a specific path so that it is accessible by the container.
	//
	// Every pod that is configured to use this container will autmoatically have access to the volume.
	Mount(path *string, storage IStorage, options *MountOptions)
}

